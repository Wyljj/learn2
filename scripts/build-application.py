def font(run, size=11, bold=False, family='宋体'):
    run.font.name = family
    run._element.get_or_add_rPr().rFonts.set(qn('w:eastAsia'), family)
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = RGBColor(0, 0, 0)

def new_doc():
    d = Document()
    s = d.sections[0]
    s.page_width, s.page_height = Cm(21), Cm(29.7)
    s.top_margin, s.bottom_margin = Cm(2.1), Cm(1.9)
    s.left_margin, s.right_margin = Cm(2.25), Cm(2.25)
    for name in ['Normal', 'Title', 'Subtitle', 'Heading 1', 'Heading 2']:
        st = d.styles[name]
        st.font.name = '宋体'
        st._element.get_or_add_rPr().rFonts.set(qn('w:eastAsia'), '宋体')
        st.font.color.rgb = RGBColor(0, 0, 0)
        pp = st._element.find(qn('w:pPr'))
        if pp is not None:
            for border in list(pp.findall(qn('w:pBdr'))): pp.remove(border)
    normal = d.styles['Normal'].paragraph_format
    normal.line_spacing = 1.35
    normal.space_after = Pt(7)
    d.styles['Normal'].font.size = Pt(11)
    for n, size in [('Title', 22), ('Heading 1', 15), ('Heading 2', 12)]:
        d.styles[n].font.size = Pt(size)
        d.styles[n].font.bold = True
    d.styles['Heading 1'].paragraph_format.space_before = Pt(10)
    d.styles['Heading 1'].paragraph_format.space_after = Pt(10)
    d.styles['Heading 2'].paragraph_format.space_before = Pt(9)
    d.styles['Heading 2'].paragraph_format.space_after = Pt(6)
    footer = s.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = footer.add_run('第 '); font(r, 9)
    f = OxmlElement('w:fldSimple'); f.set(qn('w:instr'), 'PAGE'); footer._p.append(f)
    r = footer.add_run(' 页'); font(r, 9)
    d.core_properties.author = ''
    d.core_properties.last_modified_by = ''
    d.core_properties.subject = '岗位培训工具申报准备与真实试用记录'
    return d

def p(d, text='', bold=False, size=11):
    x = d.add_paragraph()
    x.paragraph_format.widow_control = True
    font(x.add_run(text), size, bold)
    return x

def heading(d, text, level=1):
    x = d.add_paragraph(text, style=f'Heading {level}')
    for r in x.runs: font(r, 15 if level == 1 else 12, True)
    return x

def title(d, text, subtitle):
    x = d.add_paragraph(style='Title'); font(x.add_run(text), 22, True)
    x.paragraph_format.space_after = Pt(8)
    x = p(d, subtitle, size=11); x.paragraph_format.space_after = Pt(14)

def table(d, headers, rows, widths, blank_height=None):
    t = d.add_table(rows=1, cols=len(headers)); t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for i, w in enumerate(widths): t.columns[i].width = Cm(w)
    for row in t.rows:
        for i, cell in enumerate(row.cells): cell.width = Cm(widths[i])
    for i, text in enumerate(headers): t.rows[0].cells[i].text = text
    for row in rows:
        cells = t.add_row().cells
        for i, text in enumerate(row): cells[i].text = text; cells[i].width = Cm(widths[i])
    borders = OxmlElement('w:tblBorders')
    for edge in ['top','left','bottom','right','insideH','insideV']:
        b=OxmlElement('w:'+edge); b.set(qn('w:val'),'single'); b.set(qn('w:sz'),'4'); b.set(qn('w:color'),'D9D9D9'); borders.append(b)
    t._tbl.tblPr.append(borders)
    for j,row in enumerate(t.rows):
        trPr = row._tr.get_or_add_trPr()
        no_split=OxmlElement('w:cantSplit'); trPr.append(no_split)
        if j == 0:
            repeat=OxmlElement('w:tblHeader'); trPr.append(repeat)
        if blank_height and j:
            h=OxmlElement('w:trHeight'); h.set(qn('w:val'),str(int(blank_height*567))); h.set(qn('w:hRule'),'atLeast'); trPr.append(h)
        for c in row.cells:
            c.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            tcPr=c._tc.get_or_add_tcPr()
            margins=OxmlElement('w:tcMar')
            for side, val in [('top','85'),('bottom','85'),('left','105'),('right','105')]:
                item=OxmlElement('w:'+side); item.set(qn('w:w'),val); item.set(qn('w:type'),'dxa'); margins.append(item)
            tcPr.append(margins)
            if j==0:
                sh=OxmlElement('w:shd'); sh.set(qn('w:fill'),'E9EDF1'); tcPr.append(sh)
            for para in c.paragraphs:
                para.paragraph_format.line_spacing=1.15
                para.paragraph_format.space_after=Pt(1)
                for r in para.runs: font(r, 10, j==0)
    p(d, '', size=3).paragraph_format.space_after=Pt(2)
    return t

